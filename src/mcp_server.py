
import hashlib
import json
from pathlib import Path

from mcp.server.fastmcp import FastMCP

mcp = FastMCP("Groww Milestone 5")

# Project paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUTPUTS_DIR = PROJECT_ROOT / "outputs"

JSONL_PATH = OUTPUTS_DIR / "product_updates.jsonl"
MARKDOWN_PATH = OUTPUTS_DIR / "product_updates.md"
EMAIL_PATH = OUTPUTS_DIR / "customer_email_draft.md"

OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)


def payload_hash(payload: dict) -> str:
    """Calculate a stable SHA-256 hash of the proposed payload."""
    serialized = json.dumps(
        payload,
        sort_keys=True,
        ensure_ascii=False,
    )
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()


def read_existing_entries() -> list[dict]:
    """Read valid JSONL entries from the local update store."""
    if not JSONL_PATH.exists():
        return []

    entries = []
    with JSONL_PATH.open("r", encoding="utf-8") as file:
        for line in file:
            if not line.strip():
                continue
            try:
                entries.append(json.loads(line))
            except json.JSONDecodeError:
                continue

    return entries


def render_markdown_entry(record: dict) -> str:
    """Format one approved update as a readable Markdown entry."""
    themes = "\n".join(
        f"- {theme}" for theme in record["top_themes"]
    ) or "- None provided"

    bullets = "\n".join(
        f"- {bullet}" for bullet in record["explanation_bullets"]
    ) or "- None provided"

    links = "\n".join(
        f"- [{url}]({url})" for url in record["source_links"]
    ) or "- None provided"

    return (
        f"## Product Update — {record['date']}\n\n"
        f"**Approval status:** {record['approval_status']}\n\n"
        f"### Top themes\n{themes}\n\n"
        f"### Weekly product pulse\n"
        f"{record['weekly_pulse']}\n\n"
        f"### Identified fee issue\n"
        f"{record['identified_fee_issue']}\n\n"
        f"### Customer explanation\n{bullets}\n\n"
        f"### Sources\n{links}\n\n"
        f"---\n"
    )


def sync_markdown_document(entries: list[dict]) -> None:
    """Regenerate the readable document from saved approved entries."""
    approved_entries = [
        entry for entry in entries
        if entry.get("approval_status") == "APPROVED"
    ]

    content = (
        "# Groww Product Updates\n\n"
        "Local document generated by the Milestone 5 MCP prototype.\n\n"
    )

    if not approved_entries:
        content += "No approved updates yet.\n"
    else:
        for entry in approved_entries:
            content += render_markdown_entry(entry) + "\n"

    MARKDOWN_PATH.write_text(content, encoding="utf-8")


@mcp.tool()
def read_doc() -> str:
    """Read approved product updates from the local Markdown document."""
    entries = read_existing_entries()
    sync_markdown_document(entries)

    if not MARKDOWN_PATH.exists():
        return "No product updates exist yet."

    content = MARKDOWN_PATH.read_text(encoding="utf-8")
    if "No approved updates yet." in content:
        return "No product updates exist yet."

    return content


@mcp.tool()
def append_to_doc(
    date: str,
    top_themes: list[str],
    weekly_pulse: str,
    identified_fee_issue: str,
    explanation_bullets: list[str],
    source_links: list[str],
    approval_status: str,
    approval_hash: str,
) -> str:
    """Append an approved update after checking approval and payload hash."""

    payload = {
        "date": date,
        "top_themes": top_themes,
        "weekly_pulse": weekly_pulse,
        "identified_fee_issue": identified_fee_issue,
        "explanation_bullets": explanation_bullets,
        "source_links": source_links,
    }

    # Reject unapproved writes.
    if approval_status != "APPROVED":
        return (
            "Rejected: approval_status must be APPROVED. "
            "Nothing was written."
        )

    # Verify the payload is exactly the one whose hash was supplied.
    if approval_hash != payload_hash(payload):
        return (
            "Rejected: payload hash mismatch. "
            "Nothing was written."
        )

    entries = read_existing_entries()

    # Prevent duplicate entries for the same date.
    if any(entry.get("date") == date for entry in entries):
        return f"Skipped: an entry for {date} already exists."

    record = {
        **payload,
        "approval_status": "APPROVED",
    }

    # Append the structured record.
    with JSONL_PATH.open("a", encoding="utf-8") as file:
        file.write(
            json.dumps(record, ensure_ascii=False) + "\n"
        )

    # Regenerate the readable document.
    entries.append(record)
    sync_markdown_document(entries)

    # Verify the saved record can be read back.
    verified_entries = read_existing_entries()
    verified = any(
        entry.get("date") == date
        and entry.get("approval_status") == "APPROVED"
        and entry.get("weekly_pulse") == weekly_pulse
        for entry in verified_entries
    )

    if not verified:
        return (
            "Warning: the update was written, "
            "but read-back verification failed."
        )

    return (
        f"Approved update appended and verified for {date}. "
        f"Readable document: {MARKDOWN_PATH}"
    )


@mcp.tool()
def create_email_draft(
    subject: str,
    weekly_pulse: str,
    fee_explanation: str,
    approval_status: str,
) -> str:
    """Create a local Markdown email draft after approval; never send email."""

    if approval_status != "APPROVED":
        return "Rejected: approval required. No draft created."

    draft = (
        "# Customer Email Draft\n\n"
        f"**Subject:** {subject}\n\n"
        f"{weekly_pulse}\n\n"
        "## Customer Fee Clarification\n\n"
        f"{fee_explanation}\n\n"
        "**Status:** Draft only — not sent.\n"
    )

    EMAIL_PATH.write_text(draft, encoding="utf-8")

    return (
        f"Local draft saved to {EMAIL_PATH}. "
        "No email was sent."
    )


if __name__ == "__main__":
    mcp.run(transport="stdio")
